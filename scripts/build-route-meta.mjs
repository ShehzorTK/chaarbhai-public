import {readFileSync, writeFileSync} from 'node:fs';
import vm from 'node:vm';

// Keep the metadata used by animated navigation in sync with the real HTML pages.
const files = {'/':'index','/work':'work','/about':'about','/prices':'prices','/reviews':'reviews','/contact':'contact'};
const context = {window:{}, document:{addEventListener(){}}};
vm.runInNewContext(readFileSync('legal.js','utf8'), context);
const home = readFileSync('index.html','utf8');
const escape = s => s.replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;');
for (const [path, page] of Object.entries(context.window.CB_LEGAL)) {
  const description = `${page.title.split(' · ')[0]} for Chaar Bhai wedding photography and film.`;
  const url = `https://www.chaarbhai.com${path}`;
  let html = home.replace(/<title>.*?<\/title>/, `<title>${page.title}</title>`)
    .replace(/(<meta name="description" content=")[^"]*/, '$1'+escape(description))
    .replace(/(<link rel="canonical" href=")[^"]*/, '$1'+url)
    .replace(/(<meta property="og:url" content=")[^"]*/, '$1'+url)
    .replace(/(<meta (?:property="og|name="twitter):title" content=")[^"]*/g, '$1'+escape(page.title))
    .replace(/(<meta (?:property="og|name="twitter):description" content=")[^"]*/g, '$1'+escape(description))
    .replace(/<!--seo:static-->[\s\S]*?<!--\/seo:static-->/,
      `<!--seo:static--><div class="seo-static">${page.html}</div><!--/seo:static-->`);
  writeFileSync(path.slice(1)+'.html',html);
  files[path] = path.slice(1);
}
const metadata = {};
for (const [path, file] of Object.entries(files)) {
  const html = readFileSync(file+'.html','utf8');
  metadata[path] = {
    description: /<meta name="description" content="([^"]*)"/.exec(html)[1],
    structuredData: /<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(html)[1]
  };
}
writeFileSync('route-meta.js', `/* Generated by node scripts/build-route-meta.mjs. */
const ROUTE_METADATA=${JSON.stringify(metadata)};
function syncRouteMetadata(path){
  const meta=ROUTE_METADATA[path];if(!meta)return;
  const url='https://www.chaarbhai.com'+path;
  document.querySelector('link[rel="canonical"]').href=url;
  for(const selector of ['meta[name="description"]','meta[property="og:description"]','meta[name="twitter:description"]']){
    const el=document.querySelector(selector);if(el)el.content=meta.description;
  }
  for(const selector of ['meta[property="og:title"]','meta[name="twitter:title"]']){
    const el=document.querySelector(selector);if(el)el.content=document.title;
  }
  const og=document.querySelector('meta[property="og:url"]');if(og)og.content=url;
  const ld=document.querySelector('script[type="application/ld+json"]');if(ld)ld.textContent=meta.structuredData;
}
`);
